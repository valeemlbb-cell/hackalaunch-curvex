/**
 * Single source of truth: the protocol constants live in
 * `programs/curvex/src/constants.rs`. This script regenerates
 * `client/src/constants.ts` from it so the CLI can never drift from the
 * deployed program.
 *
 *   node scripts/gen-constants.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "programs/curvex/src/constants.rs"), "utf8");

const numeric = [...src.matchAll(/pub const (\w+): (u8|u64|u128) = ([0-9_]+);/g)].map(
  ([, name, ty, value]) => ({ name, value: value.replaceAll("_", ""), ty }),
);
const seeds = [...src.matchAll(/pub const (SEED_\w+): &\[u8\] = b"([^"]+)";/g)].map(
  ([, name, value]) => ({ name, value }),
);

const lines = [
  "// GENERATED BY scripts/gen-constants.mjs — DO NOT EDIT BY HAND.",
  "// Source of truth: programs/curvex/src/constants.rs",
  "",
];
for (const { name, value } of numeric) {
  lines.push(`export const ${name} = ${value}n;`);
}
lines.push("");
for (const { name, value } of seeds) {
  lines.push(`export const ${name} = Buffer.from(${JSON.stringify(value)});`);
}
lines.push("");
lines.push("export const LAMPORTS_PER_SOL = 1_000_000_000n;");
lines.push("");

writeFileSync(join(root, "client/src/constants.ts"), lines.join("\n"));
console.log(`wrote ${numeric.length} numeric + ${seeds.length} seed constants`);
